#ifndef __MYFLASH_H
#define __MYFLASH_H

#include "stm32f0xx.h"

/***************************************************************************************
**  接口数据申明
**************************************************************************************/
#define WriteFlashAddress ((uint32_t)0x0800F400) // 用户参数存储地址，0x0800F000~0x0800FFFF,共4k
#define FLASH_DATA_WORDS 7U
#define FLASH_CRC_WORDS 1U

// 扩展FlashData：前3个保留原用途，后4个存储IMEI（16字节）
typedef struct
{
	uint32_t flash_data[FLASH_DATA_WORDS];
} myflash_context_t;

extern myflash_context_t g_myflash_context;

#define FlashData (g_myflash_context.flash_data)
// IMEI在FlashData中的起始索引
#define FLASH_IMEI_INDEX 3
/***************************************************************************************
**  接口函数申明
**************************************************************************************/
uint8_t Write_Flash(uint32_t *buff, uint8_t len);
uint8_t flash_read(void);

#endif // __MYFLASH_H

